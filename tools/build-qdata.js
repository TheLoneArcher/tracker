/*
 * Regenerates qdata.js (exact page + exam source for every question) from the PYQ directory markdown.
 * Usage:  node tools/build-qdata.js path/to/GATE_PYQ_Complete_Question_Directory.md
 * It also cross-checks the directory against data.js and refuses to write if anything disagrees.
 */
const fs = require('fs'), path = require('path');
const src = process.argv[2];
if (!src) { console.error('usage: node tools/build-qdata.js <directory.md>'); process.exit(1); }
const { SUBJECTS } = require('../data.js');

const BOOK_TO_ID = {
  'algorithms': 'algo', 'calculus': 'calc', 'combinatory': 'comb', 'compiler design': 'cd', 'computer networks': 'cn',
  'computer organization and architecture': 'coa', 'data structures': 'ds', 'database management systems': 'dbms',
  'digital logic': 'dl', 'general aptitude': 'ga', 'graph theory': 'gt', 'linear algebra': 'la', 'mathematical logic': 'ml',
  'operating systems': 'os', 'probability': 'prob', 'programming': 'c', 'set theory and algebra': 'sta', 'theory of computation': 'toc'
};
const lines = fs.readFileSync(src, 'utf8').replace(/\r/g, '').split('\n');
const books = []; let b = null, t = null;
for (const l of lines) {
  let m;
  if ((m = l.match(/^## (\d+)\. (.+?) \((\d+) Questions, (\d+) Pages\)/))) { b = { name: m[2], pages: +m[4], topics: [] }; books.push(b); t = null; }
  else if ((m = l.match(/^### ([\d.]+) (.+?) \(p\. (\d+) . (\d+) \| (\d+) Questions\)/))) { t = { p0: +m[3], p1: +m[4], q: +m[5], rows: [] }; b.topics.push(t); }
  else if ((m = l.match(/^\| (\d+) \| (.+?) \| \*\*Page (\d+)\*\* \|/))) { if (t) t.rows.push({ src: m[2].trim(), page: +m[3] }); }
}
const out = {}; let problems = 0;
const fail = s => { console.error('PROBLEM: ' + s); problems++; };
books.forEach(bk => {
  const id = BOOK_TO_ID[bk.name.toLowerCase()];
  if (!id) return fail('unknown book ' + bk.name);
  const sub = SUBJECTS.find(s => s.id === id);
  const p = [], s = [], ts = [];
  bk.topics.forEach(tp => {
    if (tp.rows.length !== tp.q) fail(bk.name + ': topic header says ' + tp.q + ' questions, table has ' + tp.rows.length);
    ts.push(tp.p0);
    tp.rows.forEach(r => { p.push(r.page); s.push(r.src); });
  });
  if (p.length !== sub.questions) fail(id + ': ' + p.length + ' questions vs data.js ' + sub.questions);
  if (bk.pages !== sub.pages) fail(id + ': ' + bk.pages + ' pages vs data.js ' + sub.pages);
  if (sub.topics.length) {
    if (bk.topics.length !== sub.topics.length) fail(id + ': topic count differs');
    bk.topics.forEach((tp, i) => { if (sub.topics[i] && (sub.topics[i].q !== tp.q || sub.topics[i].s !== tp.p0)) fail(id + ' topic ' + (i + 1) + ': counts or start page differ'); });
  }
  for (let i = 1; i < p.length; i++) if (p[i] < p[i - 1]) { fail(id + ': page numbers go backwards at question ' + (i + 1)); break; }
  out[id] = { p, s };
});
if (Object.keys(out).length !== SUBJECTS.length) fail('not every subject was found');
if (problems) process.exit(1);
const js = '/* Exact page and exam source for every question, generated by tools/build-qdata.js from the PYQ directory.\n   p[k] = book page of the k-th question (in book order); s[k] = exam identifier. */\nconst QD = ' + JSON.stringify(out) + ';\nif (typeof module !== \'undefined\') module.exports = { QD };\n';
fs.writeFileSync(path.join(__dirname, '..', 'qdata.js'), js);
console.log('wrote qdata.js,', Object.keys(out).length, 'books,', Object.values(out).reduce((a, x) => a + x.p.length, 0), 'questions,', (js.length / 1024).toFixed(0) + ' KB');
